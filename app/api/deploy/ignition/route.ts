import fs from 'node:fs';
import path from 'node:path';
import { NextResponse } from 'next/server';
import { z } from 'zod';
import { synthesizeProject } from '@/lib/synthesizer';
import { listCustomModules, recordTelemetry, getDataDir } from '@/lib/db/sqlite-engine';
import { validateRuntimeEnv } from '@/lib/security/env-validator';
import {
  checkSlidingWindowRateLimit,
  resolveClientIdentifier,
  buildRateLimitHeaders,
} from '@/lib/security/rate-limiter';

const IgnitionRequestSchema = z.object({
  projectName: z
    .string()
    .min(2)
    .max(64)
    .regex(/^[a-z0-9-]+$/, 'Project name must be kebab-case alphanumeric')
    .default('antigravity-orbital-app'),
  prompt: z.string().max(500).optional(),
  moduleIds: z.array(z.string().min(2).max(64)).min(1),
  mode: z.enum(['bundle', 'materialize']).optional().default('bundle'),
});

function buildDockerComposeStack(projectName: string, hasPostgres: boolean, hasPgVector: boolean): string {
  const lines: string[] = [
    `# ============================================================================`,
    `# ${projectName.toUpperCase()} — ANTIGRAVITY ORBITAL IGNITION STACK`,
    `# Generated by POST /api/deploy/ignition`,
    `# ============================================================================`,
    `services:`,
    `  web:`,
    `    build:`,
    `      context: .`,
    `      dockerfile: Dockerfile`,
    `    container_name: ${projectName}-web`,
    `    ports:`,
    `      - "3000:7860"`,
    `    env_file:`,
    `      - .env.example`,
    `    environment:`,
    `      - NODE_ENV=production`,
    `      - PORT=7860`,
  ];

  if (hasPostgres || hasPgVector) {
    lines.push(
      `    depends_on:`,
      `      postgres-orbital:`,
      `        condition: service_healthy`,
      ``,
      `  postgres-orbital:`,
      `    image: pgvector/pgvector:pg17`,
      `    container_name: ${projectName}-pg17`,
      `    restart: unless-stopped`,
      `    ports:`,
      `      - "54322:5432"`,
      `    environment:`,
      `      POSTGRES_USER: postgres`,
      `      POSTGRES_PASSWORD: orbital_zero_trust_password`,
      `      POSTGRES_DB: orbital_core`,
      `    volumes:`,
      `      - ./supabase/migrations:/docker-entrypoint-initdb.d:ro`,
      `      - pg_orbital_data:/var/lib/postgresql/data`,
      `    healthcheck:`,
      `      test: ["CMD-SHELL", "pg_isready -U postgres -d orbital_core"]`,
      `      interval: 5s`,
      `      timeout: 5s`,
      `      retries: 5`,
      ``,
      `volumes:`,
      `  pg_orbital_data:`
    );
  }

  return lines.join('\n') + '\n';
}

function buildIgnitionScript(projectName: string, resolvedIds: string[]): string {
  return [
    `#!/usr/bin/env bash`,
    `set -euo pipefail`,
    ``,
    `echo "============================================================"`,
    `echo "  ANTIGRAVITY ORBITAL IGNITION: ${projectName}"`,
    `echo "  Active Modules (${resolvedIds.length}): ${resolvedIds.join(', ')}"`,
    `echo "============================================================"`,
    ``,
    `if [ ! -f .env.local ] && [ -f .env.example ]; then`,
    `  cp .env.example .env.local`,
    `  echo "[+] Initialized .env.local from .env.example"`,
    `fi`,
    ``,
    `echo "[+] Installing dependencies..."`,
    `npm install`,
    ``,
    `echo "[+] Verifying TypeScript AST and production Next.js 15 build..."`,
    `npm run build`,
    ``,
    `echo "[+] Ignition verified! Run 'npm run dev' or 'docker compose up --build' to launch."`,
    ``,
  ].join('\n');
}

export async function POST(request: Request) {
  const start = performance.now();
  const env = validateRuntimeEnv();
  const clientIp = resolveClientIdentifier(request);
  const rateLimit = checkSlidingWindowRateLimit(`ignition:${clientIp}`, env.RATE_LIMIT_RPM, 60_000);
  const rateHeaders = buildRateLimitHeaders(rateLimit);

  if (!rateLimit.allowed) {
    return NextResponse.json(
      { error: 'Rate limit exceeded', resetAtMs: rateLimit.resetAtMs },
      { status: 429, headers: rateHeaders }
    );
  }

  try {
    const body = await request.json();
    const parsed = IgnitionRequestSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: parsed.error.flatten() },
        { status: 400, headers: rateHeaders }
      );
    }

    const customModules = listCustomModules();
    const synthesized = synthesizeProject({
      projectName: parsed.data.projectName,
      prompt: parsed.data.prompt,
      moduleIds: parsed.data.moduleIds,
      customModules,
    });

    const resolvedSet = new Set(synthesized.resolvedIds);
    const dockerCompose = buildDockerComposeStack(
      synthesized.projectName,
      resolvedSet.has('supabase-db'),
      resolvedSet.has('pgvector-rag')
    );
    const igniteScript = buildIgnitionScript(synthesized.projectName, synthesized.resolvedIds);

    const allIgnitionFiles: Record<string, string> = {
      ...synthesized.files,
      'docker-compose.yml': dockerCompose,
      'ignite.sh': igniteScript,
    };

    if (!allIgnitionFiles['Dockerfile']) {
      allIgnitionFiles['Dockerfile'] = [
        'FROM node:22-alpine AS base',
        'WORKDIR /app',
        'COPY package*.json ./',
        'RUN npm install',
        'COPY . .',
        'RUN npm run build',
        'EXPOSE 7860',
        'ENV PORT=7860',
        'CMD ["npm", "run", "start"]',
      ].join('\n');
    }

    if (!allIgnitionFiles['.dockerignore']) {
      allIgnitionFiles['.dockerignore'] = ['node_modules', '.next', '.git', '.env*.local'].join('\n');
    }

    let pkgValid = false;
    try {
      const parsedPkg = JSON.parse(allIgnitionFiles['package.json'] || '{}') as {
        dependencies?: Record<string, string>;
      };
      pkgValid = Boolean(parsedPkg.dependencies?.next);
    } catch {
      pkgValid = false;
    }

    let tsconfigStrict = false;
    try {
      const parsedTs = JSON.parse(allIgnitionFiles['tsconfig.json'] || '{}') as {
        compilerOptions?: { strict?: boolean };
      };
      tsconfigStrict = parsedTs.compilerOptions?.strict === true;
    } catch {
      tsconfigStrict = false;
    }

    const verificationChecks = [
      {
        id: 'package-json-ast',
        label: 'package.json Next.js 15 Dependency Graph',
        passed: pkgValid,
        detail: pkgValid ? 'Verified Next.js 15 runtime manifest' : 'Missing Next.js dependency',
      },
      {
        id: 'tsconfig-ast',
        label: 'TypeScript Strict Mode Configuration',
        passed: tsconfigStrict,
        detail: tsconfigStrict ? 'compilerOptions.strict = true' : 'Strict mode disabled',
      },
      {
        id: 'dockerfile-ready',
        label: 'Multi-Stage Container Runtime (Port 7860)',
        passed: Boolean(allIgnitionFiles['Dockerfile']?.includes('7860')),
        detail: 'Node 22 Alpine container image ready',
      },
      {
        id: 'compose-stack-ready',
        label: 'Docker Compose Service Orchestration',
        passed: dockerCompose.includes('services:'),
        detail: 'Web + PostgreSQL 17 / pgvector stack verified',
      },
      {
        id: 'sha256-integrity',
        label: 'Cryptographic Bundle SHA-256 Digest',
        passed: /^[a-f0-9]{64}$/i.test(synthesized.sha256),
        detail: `SHA-256: ${synthesized.sha256.slice(0, 16)}...`,
      },
    ];

    let materializedDir: string | null = null;
    const writtenFiles: string[] = [];

    if (parsed.data.mode === 'materialize') {
      const baseTarget = path.join(getDataDir(), 'ignited-projects', synthesized.projectName);
      fs.mkdirSync(baseTarget, { recursive: true });

      for (const [relPath, content] of Object.entries(allIgnitionFiles)) {
        const cleanRel = relPath.replace(/^(\.\.(\/|\\|$))+/, '').replace(/^\/+/, '');
        const absFile = path.join(baseTarget, cleanRel);
        fs.mkdirSync(path.dirname(absFile), { recursive: true });
        fs.writeFileSync(absFile, content, 'utf8');
        if (cleanRel === 'ignite.sh') {
          fs.chmodSync(absFile, 0o755);
        }
        writtenFiles.push(cleanRel);
      }
      materializedDir = baseTarget;
    }

    recordTelemetry({
      eventType: parsed.data.mode === 'materialize' ? 'DEPLOY_MATERIALIZE' : 'DEPLOY_IGNITION',
      projectName: synthesized.projectName,
      moduleCount: synthesized.resolvedIds.length,
      filesCount: Object.keys(allIgnitionFiles).length,
      bundleBytes: synthesized.bundleBytes,
      durationMs: performance.now() - start,
    });

    return NextResponse.json(
      {
        status: 'ignited',
        mode: parsed.data.mode,
        projectName: synthesized.projectName,
        resolvedIds: synthesized.resolvedIds,
        sha256: synthesized.sha256,
        filesCount: Object.keys(allIgnitionFiles).length,
        materializedDir,
        writtenFilesCount: writtenFiles.length,
        dockerCompose,
        igniteScript,
        verificationChecks,
      },
      { status: 200, headers: rateHeaders }
    );
  } catch (err) {
    return NextResponse.json(
      { error: `Deployment ignition failed: ${err instanceof Error ? err.message : String(err)}` },
      { status: 400, headers: rateHeaders }
    );
  }
}

function collectFilesRecursive(dirPath: string, baseDir = dirPath): { files: string[]; totalBytes: number } {
  let files: string[] = [];
  let totalBytes = 0;
  if (!fs.existsSync(dirPath)) return { files, totalBytes };

  for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
    const fullPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      const sub = collectFilesRecursive(fullPath, baseDir);
      files = files.concat(sub.files);
      totalBytes += sub.totalBytes;
    } else if (entry.isFile()) {
      const stat = fs.statSync(fullPath);
      files.push(path.relative(baseDir, fullPath));
      totalBytes += stat.size;
    }
  }
  return { files, totalBytes };
}

export async function GET() {
  const rootDir = path.join(getDataDir(), 'ignited-projects');
  if (!fs.existsSync(rootDir)) {
    return NextResponse.json({ status: 'online', materializedProjects: [] }, { status: 200 });
  }

  const entries = fs.readdirSync(rootDir, { withFileTypes: true }).filter((d) => d.isDirectory());
  const materializedProjects = entries.map((dir) => {
    const projectPath = path.join(rootDir, dir.name);
    const stat = fs.statSync(projectPath);
    const { files, totalBytes } = collectFilesRecursive(projectPath);
    return {
      projectName: dir.name,
      path: projectPath,
      filesCount: files.length,
      totalBytes,
      updatedAt: stat.mtime.toISOString(),
      files: files.sort(),
    };
  });

  return NextResponse.json({ status: 'online', materializedProjects }, { status: 200 });
}

export async function DELETE(request: Request) {
  const url = new URL(request.url);
  const projectName = url.searchParams.get('projectName') || '';
  if (!/^[a-z0-9-]+$/.test(projectName)) {
    return NextResponse.json({ error: 'Invalid projectName parameter' }, { status: 400 });
  }

  const targetDir = path.join(getDataDir(), 'ignited-projects', projectName);
  if (!fs.existsSync(targetDir)) {
    return NextResponse.json({ deleted: false, projectName }, { status: 404 });
  }

  fs.rmSync(targetDir, { recursive: true, force: true });
  return NextResponse.json({ deleted: true, projectName }, { status: 200 });
}
